(* ======================================================================
   CONTRACT: harness/x_decode.c, generated by quickproof/tools/new_contract.py.

   The theorem is QuickProof.Contract.harness_safe of the whole program: the
   harness harness/x_decode.c linked with the units it needs (per-law linking,
   LINK=per-law in quickproof.conf; docs/LINKING.md of the framework):
     crypto/punycode.c, patch/units/packet_ext.c, patch/shim/ossl_shim.c, quickproof/libc/libc.c.
   By VST's adequacy theorem, in the honest external world QuickProof.Env: for
   every value the nondet_* functions may return, no execution has undefined
   behaviour; the harness executes undefined behaviour exactly when one of
   its checks fails, so the theorem says its checks hold in every execution.
   What the checks are is written in the harness file.
   ====================================================================== *)

(* THE UNITS (computed, quickproof/tools/link_units.py): the closure of the
   harness under references.  A unit is linked when it defines a global (a
   function with a body, a variable with an initialiser) that a linked unit
   references without defining it, and then with all its definitions.  So
   every global this program references is resolved as in the program of all
   units; the units left out are referenced by no linked unit:
     quickproof/libc/malloc_unit.c. *)

Require Import VST.floyd.proofauto.
Require Import VST.floyd.VSU.
Require Import QuickProof.Contract.
Require QuickProof.Link.
Require OpensslPunycode.units.Punycode.
Require OpensslPunycode.units.Packet.
Require OpensslPunycode.units.Shim.
Require OpensslPunycode.units.Libc.
Require OpensslPunycode.harness.x_decode.code.

Module Harness.
  #[local] Instance CS : compspecs. make_compspecs OpensslPunycode.harness.x_decode.code.prog. Defined.
  Definition qp := ltac:(QPprog OpensslPunycode.harness.x_decode.code.prog).
End Harness.

(* The link must succeed (`Errors.OK`); the order is irrelevant. *)
Definition link_Packet := ltac:(QPlink_progs Packet.qp Punycode.qp).
Definition link_Shim := ltac:(QPlink_progs Shim.qp link_Packet).
Definition link_Libc := ltac:(QPlink_progs Libc.qp link_Shim).
Definition whole_prog := ltac:(QPlink_progs Harness.qp link_Libc).

(* The globals whole_prog declares without defining, besides the functions of
   the environment with their signatures (QuickProof.Link.undefined_globals):
   exactly those that no unit of the project defines, as in the program of all
   units.  By QuickProof.Link.honest_rejects_foreign the environment gives such an
   external function no behaviour: a proved program never calls one. *)
Local Open Scope string_scope.
Lemma whole_prog_undefined : QuickProof.Link.undefined_globals_are whole_prog
  [ "__builtin_debug"
  ]%list = true.
Proof. vm_compute. reflexivity. Qed.

