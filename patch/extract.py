#!/usr/bin/env python3
"""patch/extract.py [--check] TREE: the WPACKET functions of crypto/packet.c that ossl_a2ulabel reaches, verbatim.

crypto/packet.c as a whole is not part of the code under test: most of it is the growable-buffer, sub-packet,
length-prefix, DER and QUIC machinery, which ossl_a2ulabel never calls, and compiling it would pull in BUF_MEM,
the error stack and the QUIC variable-length integers.  The ten functions (and the macro GETBUF) that
ossl_a2ulabel reaches through WPACKET_init_static_len, WPACKET_memcpy, WPACKET_put_bytes_u8 and WPACKET_cleanup
are copied verbatim, in upstream's order, into patch/units/packet_ext.c.

  extract.py TREE          write patch/units/packet_ext.c from TREE/crypto/packet.c
  extract.py --check TREE  check that every function of patch/units/packet_ext.c and every verbatim part of the
                           header shim patch/include/ is byte-identical to upstream (exit 1 otherwise)
TREE: an OpenSSL tree at project.conf's COMMIT (e.g. `tools/qp tree openssl-punycode --orig --out DIR`).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
# (name, kind): 'f' a function definition, 'm' a #define (possibly continued with backslashes)
ITEMS = [('DEFAULT_BUF_SIZE', 'm'), ('WPACKET_allocate_bytes', 'f'), ('GETBUF', 'm'), ('WPACKET_reserve_bytes', 'f'),
         ('maxmaxsize', 'f'), ('wpacket_intern_init_len', 'f'), ('WPACKET_init_static_len', 'f'), ('put_value', 'f'),
         ('WPACKET_put_bytes__', 'f'), ('WPACKET_memcpy', 'f'), ('WPACKET_get_curr', 'f'), ('WPACKET_cleanup', 'f')]
HEADER = '''/*
 * openssl-punycode: functions of OpenSSL's crypto/packet.c (openssl-3.6.5), VERBATIM.
 *
 * Generated by patch/extract.py from upstream; `patch/extract.py --check TREE` checks that every function and
 * macro below is byte-identical to upstream's.  They are what ossl_a2ulabel (crypto/punycode.c) reaches through
 * the WPACKET API: WPACKET_init_static_len (with maxmaxsize and wpacket_intern_init_len), WPACKET_memcpy,
 * WPACKET_put_bytes__ (WPACKET_put_bytes_u8, with put_value), WPACKET_allocate_bytes, WPACKET_reserve_bytes,
 * WPACKET_get_curr (with the macro GETBUF) and WPACKET_cleanup, in upstream's order.  They are code under test.
 * They are compiled against the header shim patch/include/ (internal/cryptlib.h: OPENSSL_zalloc and OPENSSL_free;
 * internal/packet.h: the WPACKET structures, with `endfirst` a plain unsigned int instead of a 1-bit bit-field).
 *
 * Copyright 2015-2025 The OpenSSL Project Authors. All Rights Reserved.
 *
 * Licensed under the Apache License 2.0 (the "License").  You may not use
 * this file except in compliance with the License.  You can obtain a copy
 * in the file LICENSE.txt in the source distribution or at
 * https://www.openssl.org/source/license.html
 */

#include "internal/cryptlib.h"
#include "internal/packet.h"
'''


def function(src, name):
    """The definition of `name` in OpenSSL style: `type name(` at column 0, body up to `}` at column 0."""
    m = re.search(r'^(?:static )?[A-Za-z_][\w \*]*?\b%s\(.*?\n}\n' % re.escape(name), src, re.M | re.S)
    if not m:
        sys.exit('extract.py: function %s not found' % name)
    return m.group(0)


def macro(src, name):
    m = re.search(r'^#define %s\b(?:[^\n]*\\\n)*[^\n]*\n' % re.escape(name), src, re.M)
    if not m:
        sys.exit('extract.py: macro %s not found' % name)
    return m.group(0)


def struct(src, tag):
    m = re.search(r'^struct %s \{\n.*?\n\};\n' % re.escape(tag), src, re.M | re.S)
    if not m:
        sys.exit('extract.py: struct %s not found' % tag)
    return m.group(0)


def proto(src, name):
    m = re.search(r'^[A-Za-z_][\w \*]*?\b%s\([^;{]*\);\n' % re.escape(name), src, re.M)
    if not m:
        sys.exit('extract.py: prototype %s not found' % name)
    return m.group(0)


def item(src, name, kind):
    return function(src, name) if kind == 'f' else macro(src, name)


def main():
    args = sys.argv[1:]
    check = bool(args) and args[0] == '--check'
    if check:
        args = args[1:]
    if len(args) != 1:
        sys.exit(__doc__)
    tree = args[0]
    rd = lambda p: open(os.path.join(tree, p)).read()
    pkt_c = rd('crypto/packet.c')
    out = os.path.join(HERE, 'units', 'packet_ext.c')
    if not check:
        body = HEADER + ''.join('\n' + item(pkt_c, n, k) for n, k in ITEMS)
        open(out, 'w').write(body)
        print('wrote', out)
    ok = True

    def need(text, where, what):
        nonlocal ok
        if text not in open(os.path.join(HERE, where)).read():
            print('DIFFERS from upstream: %s (patch/%s)' % (what, where))
            ok = False

    for n, k in ITEMS:
        need(item(pkt_c, n, k), 'units/packet_ext.c', n)
    # the verbatim parts of the header shim
    common = rd('include/internal/common.h')
    m = re.search(r'^#if defined\(__GNUC__\) \|\| defined\(__clang__\)\n#define ossl_likely.*?^#endif\n', common, re.M | re.S)
    need(m.group(0) if m else '<ossl_likely block missing upstream>', 'include/internal/common.h', 'ossl_likely block')
    need('#define ossl_assert(x) ossl_likely((x) != 0)\n', 'include/internal/common.h', 'ossl_assert (NDEBUG)')
    if '#ifdef NDEBUG\n#define ossl_assert(x) ossl_likely((x) != 0)\n' not in common:
        print('DIFFERS from upstream: ossl_assert under NDEBUG (include/internal/common.h)')
        ok = False
    need(macro(common, 'HAS_PREFIX'), 'include/internal/common.h', 'HAS_PREFIX')
    need(macro(common, 'HAS_CASE_PREFIX'), 'include/internal/common.h', 'HAS_CASE_PREFIX')
    crypto_h = rd('include/openssl/crypto.h.in')
    need(macro(crypto_h, 'OPENSSL_zalloc'), 'include/internal/cryptlib.h', 'OPENSSL_zalloc')
    need(macro(crypto_h, 'OPENSSL_free'), 'include/internal/cryptlib.h', 'OPENSSL_free')
    need(proto(crypto_h, 'OPENSSL_strncasecmp'), 'include/internal/common.h', 'prototype of OPENSSL_strncasecmp')
    macros_h = rd('include/openssl/macros.h')
    if '#ifdef OPENSSL_NO_FILENAMES\n#define OPENSSL_FILE ""\n#define OPENSSL_LINE 0\n' not in macros_h:
        print('DIFFERS from upstream: OPENSSL_FILE/OPENSSL_LINE under OPENSSL_NO_FILENAMES (include/openssl/macros.h)')
        ok = False
    need('#define OPENSSL_FILE ""\n#define OPENSSL_LINE 0\n', 'include/internal/cryptlib.h', 'OPENSSL_FILE, OPENSSL_LINE')
    packet_h = rd('include/internal/packet.h')
    need(struct(packet_h, 'wpacket_sub'), 'include/internal/packet.h', 'struct wpacket_sub')
    wst = struct(packet_h, 'wpacket_st')
    widened = wst.replace('    unsigned int endfirst : 1;\n',
                          '    unsigned int endfirst; /* quickproof: unsigned int endfirst : 1; (VST has no bit-fields) */\n')
    if widened == wst:
        print('upstream struct wpacket_st has no `unsigned int endfirst : 1;` any more')
        ok = False
    need(widened, 'include/internal/packet.h', 'struct wpacket_st (endfirst widened)')
    need(macro(packet_h, 'WPACKET_put_bytes_u8'), 'include/internal/packet.h', 'WPACKET_put_bytes_u8')
    for f in ('WPACKET_init_static_len', 'WPACKET_allocate_bytes', 'WPACKET_reserve_bytes', 'WPACKET_put_bytes__',
              'WPACKET_memcpy', 'WPACKET_get_curr', 'WPACKET_cleanup'):
        need(proto(packet_h, f), 'include/internal/packet.h', 'prototype of ' + f)
    need(struct(rd('include/openssl/buffer.h'), 'buf_mem_st'), 'include/internal/packet.h', 'struct buf_mem_st')
    e_os2 = rd('include/openssl/e_os2.h')
    if not re.search(r'__STDC_VERSION__ >= 199901L\n/\* just use inline \*/\n#define ossl_inline inline\n', e_os2):
        print('DIFFERS from upstream: ossl_inline for C99 (include/openssl/e_os2.h)')
        ok = False
    print('verbatim copies: %s' % ('identical to upstream' if ok else 'NOT identical'))
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()
